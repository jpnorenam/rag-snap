package analysis

import (
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/jpnorenam/rag-snap/cmd/cli/basic/chat"
	"gopkg.in/yaml.v3"
)

// Provenance records how a manifest was produced, written into the file's header
// comment so that a manifest's origin is readable from the manifest itself.
type Provenance struct {
	Model     string
	Documents []DocumentReport

	// ShortfallAccepted is set when the operator accepted fewer questions than triage
	// estimated. It is written into the header so the decision travels with the file.
	ShortfallAccepted *ShortfallAcceptance
}

// ShortfallAcceptance records an operator's decision to continue past a shortfall.
type ShortfallAcceptance struct {
	Expected int `json:"expected"`
	Produced int `json:"produced"`
}

// HeaderLine is the provenance line recording the acceptance, shared by every surface
// that writes a generated manifest so the CLI file and a UI download say the same thing.
func (a ShortfallAcceptance) HeaderLine() string {
	return fmt.Sprintf("Question count accepted by the operator below the triage estimate: %d produced, about %d estimated",
		a.Produced, a.Expected)
}

// WriteManifest writes a generated manifest to path.
//
// It lives here rather than in the rfp package because a generated manifest is a
// chat.BatchManifest — it carries a prompt and a populated domains block, which the
// extraction path's rfp.Manifest does not — and rfp cannot import chat. The header
// mirrors rfp.WriteManifest's convention so both kinds of generated file look alike.
//
// Unlike the extraction path, no commented-out domains stub is written: the domains
// block here is real, and a stub beneath it would be confusing rather than helpful.
func WriteManifest(path string, m *chat.BatchManifest, p Provenance) error {
	normalise(m)

	f, err := os.Create(path)
	if err != nil {
		return fmt.Errorf("creating file: %w", err)
	}
	defer f.Close()

	if _, err := f.WriteString(manifestHeader(m, p)); err != nil {
		return fmt.Errorf("writing header: %w", err)
	}

	enc := yaml.NewEncoder(f)
	enc.SetIndent(2)
	if err := enc.Encode(m); err != nil {
		return fmt.Errorf("encoding YAML: %w", err)
	}
	return enc.Close()
}

func manifestHeader(m *chat.BatchManifest, p Provenance) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by rag-cli answer batch --build --analyze on %s\n",
		time.Now().UTC().Format("2006-01-02 15:04:05 UTC"))
	if p.Model != "" {
		fmt.Fprintf(&b, "# Analysis model: %s\n", p.Model)
	}
	for _, d := range p.Documents {
		fmt.Fprintf(&b, "# Source: %s (%s, %s)\n", d.Filename, d.Format, d.Path)
	}
	fmt.Fprintf(&b, "# %d questions, %d domains\n", len(m.Questions), len(m.Domains))
	if p.ShortfallAccepted != nil {
		fmt.Fprintf(&b, "# %s\n", p.ShortfallAccepted.HeaderLine())
	}
	b.WriteString("#\n")
	b.WriteString("# Review before running. The prompt and the domain contexts are the model's work\n")
	b.WriteString("# and are worth reading; the answer-length and gap-reporting rules at the end of\n")
	b.WriteString("# the prompt are added by rag-cli and are checked for by 'answer batch --check'.\n")
	b.WriteString("#\n")
	return b.String()
}

// normalise cleans up a generated manifest so it encodes as a readable file a person
// can hand-edit.
//
// The trailing-whitespace pass is the load-bearing part. A multi-line string encodes as
// a literal block — "prompt: |" — which is what makes a two-thousand-word prompt
// legible and editable. But a single line ending in a space forces the encoder to fall
// back to a double-quoted scalar with every newline escaped, turning the whole prompt
// into one unreadable line. Models emit trailing spaces routinely, so this is the
// difference between a file an operator will edit and one they will not.
func normalise(m *chat.BatchManifest) {
	m.Prompt = stripTrailingSpace(m.Prompt)
	for i := range m.Domains {
		m.Domains[i].Context = stripTrailingSpace(m.Domains[i].Context)
		m.Domains[i].Match = strings.TrimSpace(m.Domains[i].Match)
	}
	for i := range m.Questions {
		m.Questions[i].Question = stripTrailingSpace(m.Questions[i].Question)
		m.Questions[i].ID = strings.TrimSpace(m.Questions[i].ID)
		m.Questions[i].Source = strings.TrimSpace(m.Questions[i].Source)
	}
}

// stripTrailingSpace removes trailing whitespace from every line and collapses runs of
// more than one blank line, leaving a single trailing newline.
func stripTrailingSpace(s string) string {
	if s == "" {
		return ""
	}
	lines := strings.Split(strings.ReplaceAll(s, "\r\n", "\n"), "\n")
	out := make([]string, 0, len(lines))
	blank := 0
	for _, line := range lines {
		line = strings.TrimRight(line, " \t")
		if line == "" {
			blank++
			if blank > 1 {
				continue
			}
		} else {
			blank = 0
		}
		out = append(out, line)
	}
	// Drop trailing blank lines; the encoder adds the final newline itself.
	for len(out) > 0 && out[len(out)-1] == "" {
		out = out[:len(out)-1]
	}
	return strings.Join(out, "\n") + "\n"
}
